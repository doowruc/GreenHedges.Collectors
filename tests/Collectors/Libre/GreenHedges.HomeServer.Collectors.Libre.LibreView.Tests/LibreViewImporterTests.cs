using GreenHedges.HomeServer.Collectors.Libre.Storage;
using Microsoft.Data.Sqlite;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.Extensions.Time.Testing;

namespace GreenHedges.HomeServer.Collectors.Libre.LibreView.Tests;

public sealed class LibreViewImporterTests : IDisposable
{
    private static readonly TimeZoneInfo London = TimeZoneInfo.FindSystemTimeZoneById("Europe/London");

    // Synthetic export in LibreView's real layout (made-up values; no real data).
    private const string Header =
        "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin Value (units),Notes,Strip Glucose mmol/L,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units),Historic Ketone mmol/L,Scan Ketone mmol/L";

    private static string Row(string timestamp, string type, string historic = "", string scan = "", string longInsulin = "", string carbs = "", string notes = "") =>
        $"FreeStyle LibreLink,TEST-DEVICE,{timestamp},{type},{historic},{scan},,,,{carbs},,,{longInsulin},{(notes.Contains(',') ? $"\"{notes}\"" : notes)},,,,,,,";

    private readonly string _dir = Path.Combine(Path.GetTempPath(), $"librecollector-lv-{Guid.NewGuid():N}");
    private readonly FakeTimeProvider _time = new(new DateTimeOffset(2026, 10, 17, 12, 0, 0, TimeSpan.Zero));
    private readonly GlucoseArchive _archive;

    public LibreViewImporterTests()
    {
        Directory.CreateDirectory(_dir);
        _archive = new GlucoseArchive(Path.Combine(_dir, "archive.db"));
    }

    public void Dispose()
    {
        SqliteConnection.ClearAllPools();
        Directory.Delete(_dir, recursive: true);
    }

    private LibreViewImporter Importer() => new(_archive, _time, NullLogger<LibreViewImporter>.Instance);

    private async Task<string> WriteCsvAsync(params string[] rows)
    {
        var path = Path.Combine(_dir, "export.csv");
        await File.WriteAllLinesAsync(
            path,
            ["Glucose Data,Generated on,17-10-2026 09:00 UTC,Generated by,Test Person", Header, .. rows]);
        return path;
    }

    [Fact]
    public async Task Imports_readings_scans_and_events_with_utc_times()
    {
        await _archive.InitialiseAsync(CancellationToken.None);
        var path = await WriteCsvAsync(
            Row("05-12-2023 12:41", "0", historic: "6.8"),             // GMT: 12:41Z
            Row("17-10-2026 03:26", "0", historic: "4.9"),             // BST: 02:26Z
            Row("17-10-2026 10:24", "1", scan: "8.3"),
            Row("17-10-2026 03:41", "0", historic: "2.2"),             // LO floor
            Row("16-10-2026 21:00", "4", longInsulin: "14"),
            Row("16-10-2026 18:00", "5", carbs: "45"),
            Row("16-10-2026 18:05", "6", notes: "Walk, then dinner"),  // quoted field with a comma
            Row("16-10-2026 18:06", "6"));                             // empty type-6 row

        var result = await Importer().ImportAsync(path, London);

        Assert.Equal(8, result.RowsRead);
        Assert.Equal(3, result.ReadingsImported);
        Assert.Equal(1, result.ScansImported);
        Assert.Equal(3, result.EventsImported);
        Assert.Equal(1, result.SkippedEmpty);
        Assert.Equal(new DateTimeOffset(2023, 12, 5, 12, 41, 0, TimeSpan.Zero), result.FirstUtc);
        var events = await _archive.CountEventsAsync(CancellationToken.None);
        Assert.Equal(3, events);

        var rows = await _archive.ReadAfterAsync(0, 100, TimeSpan.FromMinutes(2), CancellationToken.None);
        var gmt = Assert.Single(rows, r => r.Reading.TimestampLocal == "05-12-2023 12:41").Reading;
        Assert.Equal(new DateTimeOffset(2023, 12, 5, 12, 41, 0, TimeSpan.Zero), gmt.TimestampUtc);
        Assert.Equal(ReadingSource.LibreView, gmt.Source);
        Assert.Equal(6.8 * 18, gmt.ValueMgPerDl, 6);
        Assert.Null(gmt.TrendArrow);
        Assert.Contains("\"Historic Glucose mmol/L\":\"6.8\"", gmt.RawJson);
        Assert.DoesNotContain("Test Person", gmt.RawJson);

        var bst = Assert.Single(rows, r => r.Reading.TimestampLocal == "17-10-2026 03:26").Reading;
        Assert.Equal(new DateTimeOffset(2026, 10, 17, 2, 26, 0, TimeSpan.Zero), bst.TimestampUtc);

        Assert.True(Assert.Single(rows, r => r.Reading.TimestampLocal == "17-10-2026 03:41").Reading.IsLow);
        Assert.Equal(ReadingSource.LibreViewScan, Assert.Single(rows, r => r.Reading.TimestampLocal == "17-10-2026 10:24").Reading.Source);
    }

    [Fact]
    public async Task Autumn_ambiguous_hour_is_skipped_and_counted()
    {
        await _archive.InitialiseAsync(CancellationToken.None);
        var path = await WriteCsvAsync(
            Row("26-10-2025 00:47", "0", historic: "5.0"),
            Row("26-10-2025 01:02", "0", historic: "5.1"),   // happens twice (BST then GMT)
            Row("26-10-2025 01:03", "0", historic: "5.2"),
            Row("26-10-2025 02:03", "0", historic: "5.3"));  // after the change: GMT, 02:03Z

        var result = await Importer().ImportAsync(path, London);

        Assert.Equal(2, result.ReadingsImported);
        Assert.Equal(2, result.SkippedAmbiguousTime);
        Assert.Equal(new DateTimeOffset(2025, 10, 26, 2, 3, 0, TimeSpan.Zero), result.LastUtc);
    }

    [Fact]
    public async Task Reimporting_the_same_file_adds_nothing()
    {
        await _archive.InitialiseAsync(CancellationToken.None);
        var path = await WriteCsvAsync(
            Row("17-10-2026 03:26", "0", historic: "4.9"),
            Row("17-10-2026 10:24", "1", scan: "8.3"),
            Row("16-10-2026 21:00", "4", longInsulin: "14"));

        await Importer().ImportAsync(path, London);
        var second = await Importer().ImportAsync(path, London);

        Assert.Equal(0, second.ReadingsImported + second.ScansImported + second.EventsImported);
        Assert.Equal(1, second.ReadingsAlreadyPresent);
        Assert.Equal(1, second.ScansAlreadyPresent);
        Assert.Equal(1, second.EventsAlreadyPresent);
        Assert.Equal(1, await _archive.CountEventsAsync(CancellationToken.None));
    }

    [Fact]
    public async Task Unparseable_timestamps_are_counted_not_fatal()
    {
        await _archive.InitialiseAsync(CancellationToken.None);
        var path = await WriteCsvAsync(
            Row("2026-10-17 03:26", "0", historic: "4.9"),
            Row("17-10-2026 03:41", "0", historic: "5.1"));

        var result = await Importer().ImportAsync(path, London);

        Assert.Equal(1, result.SkippedUnparseable);
        Assert.Equal(1, result.ReadingsImported);
    }

    [Fact]
    public async Task Rejects_a_file_that_is_not_a_glucose_export()
    {
        var path = Path.Combine(_dir, "other.csv");
        await File.WriteAllLinesAsync(path, ["Title", "A,B,C", "1,2,3"]);

        await Assert.ThrowsAsync<InvalidDataException>(() => Importer().ImportAsync(path, London));
    }
}
